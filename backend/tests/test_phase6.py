"""CAIOS Phase 6 unit tests — deliverable builders + local storage.

No database: the generators are pure functions of (kind, title, spec) and the
LocalFileStorage adapter is a plain directory. Every artefact is reopened and
structurally verified — a builder that "ran without error" proves nothing
until the format reads back with the expected content.

Run from backend/:  python3 tests/test_phase6.py
"""

import io
import os
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

failures: list[str] = []


def check(name, cond, detail=""):
    print(("PASS " if cond else "FAIL ") + name + (f"  — {detail}" if detail and not cond else ""))
    if not cond:
        failures.append(name)


from app.deliverables.generate import (  # noqa: E402
    MIME_BY_KIND, SpecError, build_deliverable, checksum, validate_spec)

SPEC = {
    "meta": {"prepared_for": "Example (Pty) Ltd", "period": "Q3 2026", "author": "CAIOS"},
    "sections": [
        {"heading": "Findings",
         "body": "Revenue grew 12% period on period.\n\nMargins compressed by 2 points.",
         "bullets": ["Verified: sales mix shift", "Estimate: FX impact ~0.8 pts"]},
        {"heading": "Data gaps", "body": "No stock-count data for September.", "bullets": []},
    ],
    "tables": [
        {"title": "Revenue by line",
         "columns": ["Line", "Q2", "Q3", "Var"],
         "rows": [["Product sales", 1200, 1350, "+12.5%"],
                  ["Services", 400, 390, "-2.5%"],
                  ["=SUM(A2:A3)", 1600, 1740, "+8.8%"]]},
    ],
}

# ── 1. Spec validation ───────────────────────────────────────────────────────
clean = validate_spec(SPEC)
check("spec validates and keeps 2 sections / 1 table",
      len(clean["sections"]) == 2 and len(clean["tables"]) == 1)

for name, bad in [
    ("empty spec rejected", {}),
    ("row length mismatch rejected", {"tables": [{"columns": ["A", "B"], "rows": [["x"]]}]}),
    ("wrong type rejected", {"sections": "nope"}),
]:
    try:
        validate_spec(bad)
        check(name, False, "no SpecError raised")
    except SpecError as e:
        check(name, True, str(e))

try:
    build_deliverable("docx-does-not-exist", "t", SPEC)
    check("unknown kind rejected", False)
except SpecError:
    check("unknown kind rejected", True)

# ── 2. Markdown ──────────────────────────────────────────────────────────────
md, mime, ext = build_deliverable("md", "Q3 Variance Brief", SPEC)
text = md.decode("utf-8")
check("md: title + headings + footer", "# Q3 Variance Brief" in text
      and "## Findings" in text and "Generated by CAIOS" in text)
check("md: table pipes", "| Line | Q2 | Q3 | Var |" in text)
check("md: mime/ext", mime == MIME_BY_KIND["md"] and ext == "md")

# ── 3. DOCX round-trip ───────────────────────────────────────────────────────
docx_bytes, mime, ext = build_deliverable("docx", "Q3 Variance Report", SPEC)
from docx import Document  # noqa: E402
doc = Document(io.BytesIO(docx_bytes))
headings = [p.text for p in doc.paragraphs
            if p.style.name == "Title" or p.style.name.startswith("Heading")]
tables = doc.tables
check("docx: title heading", headings and headings[0] == "Q3 Variance Report", str(headings[:3]))
check("docx: section headings present", "Findings" in headings and "Data gaps" in headings)
check("docx: table 4x4 with header", len(tables) == 1 and len(tables[0].rows) == 4
      and tables[0].rows[0].cells[0].text == "Line")
check("docx: governance footer", any("Generated by CAIOS" in p.text for p in doc.paragraphs))

# ── 4. XLSX round-trip (incl. formula-injection guard) ──────────────────────
xlsx_bytes, mime, ext = build_deliverable("xlsx", "Q3 Variance Workbook", SPEC)
from openpyxl import load_workbook  # noqa: E402
wb = load_workbook(io.BytesIO(xlsx_bytes))
check("xlsx: Summary + one sheet per table",
      wb.sheetnames == ["Summary", "Revenue by line"], str(wb.sheetnames))
check("xlsx: summary title", wb["Summary"]["A1"].value == "Q3 Variance Workbook")
ws = wb["Revenue by line"]
check("xlsx: header bold + freeze panes", ws["A1"].font.bold and ws.freeze_panes == "A2")
check("xlsx: formula guard stores text, not formula",
      isinstance(ws["A4"].value, str) and ws["A4"].value.startswith("'="),
      repr(ws["A4"].value))
check("xlsx: numeric cell kept numeric", ws["B2"].value == 1200)

# ── 5. PDF round-trip (incl. latin-1 sanitisation) ──────────────────────────
pdf_bytes, mime, ext = build_deliverable("pdf", "Q3 Variance Report", SPEC)
check("pdf: magic header", pdf_bytes[:5] == b"%PDF-")
from pypdf import PdfReader  # noqa: E402
reader = PdfReader(io.BytesIO(pdf_bytes))
pdf_text = "".join(page.extract_text() or "" for page in reader.pages)
check("pdf: 1+ pages, title + table text extract", len(reader.pages) >= 1
      and "Q3 Variance Report" in pdf_text and "Revenue by line" in pdf_text)
weird = {"sections": [{"heading": "Café résumé ✓ 🙂", "body": "naïve façade —策略", "bullets": []}],
         "tables": [], "meta": {}}
try:
    weird_bytes, _, _ = build_deliverable("pdf", "Sanitisation", weird)
    weird_text = "".join(p.extract_text() or "" for p in PdfReader(io.BytesIO(weird_bytes)).pages)
    check("pdf: unicode transliterated, never crashes", "Cafe resume" in weird_text
          and len(weird_bytes) > 500)
except Exception as e:  # noqa: BLE001
    check("pdf: unicode transliterated, never crashes", False, str(e))

# ── 6. Checksum helper ───────────────────────────────────────────────────────
check("checksum is sha256 hex", len(checksum(md)) == 64
      and checksum(md) == checksum(build_deliverable("md", "Q3 Variance Brief", SPEC)[0]))

# ── 7. LocalFileStorage adapter ──────────────────────────────────────────────
from app.adapters.storage_adapter import LocalFileStorage  # noqa: E402
with tempfile.TemporaryDirectory() as tmp:
    st = LocalFileStorage(tmp)
    stored = st.put("company-knowledge/deliverables/o1/d1.md", md, content_type="text/markdown")
    check("local storage: put/get round-trip", st.get(stored.key) == md and st.exists(stored.key))
    st.delete(stored.key)
    check("local storage: delete", not st.exists(stored.key))
    try:
        st.put("../../etc/passwd", b"x")
        check("local storage: traversal refused", False)
    except ValueError:
        check("local storage: traversal refused", True)

# ── 8. Storage key governance prefixes ───────────────────────────────────────
from app.deliverables.handlers import deliverable_key  # noqa: E402
import uuid as _uuid  # noqa: E402
did = _uuid.uuid4()
check("keys: company scope under company-knowledge",
      deliverable_key("org-a", "company", None, did, "xlsx")
      == f"company-knowledge/deliverables/org-a/{did}.xlsx")
check("keys: client scope under client prefix",
      deliverable_key("org-a", "client", "eng-9", did, "pdf")
      == f"clients/org-a/eng-9/deliverables/{did}.pdf")

print()
print("RESULT:", "ALL PASS" if not failures else f"FAILURES: {failures}")
sys.exit(1 if failures else 0)
